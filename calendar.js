/* =========================================
   DATE FUNCTIONS
========================================= */

function dateKey(date) {

    const year =
        date.getFullYear();

    const month =
        String(date.getMonth() + 1)
            .padStart(2, "0");

    const day =
        String(date.getDate())
            .padStart(2, "0");

    return `${year}-${month}-${day}`;

}


function formatDate(dateString) {

    const date =
        new Date(dateString + "T12:00:00");

    return date.toLocaleDateString(
        "en-US",
        {
            weekday: "long",
            month: "long",
            day: "numeric",
            year: "numeric"
        }
    );

}


/* =========================================
   SEMESTER
========================================= */

function getSemester(date) {

    const year =
        date.getFullYear();

    const month =
        date.getMonth();


    if (
        (year === 2026 && month >= 8) ||
        (year === 2027 && month === 0)
    ) {

        return "First Semester";

    }


    if (
        year === 2027 &&
        month >= 1 &&
        month <= 5
    ) {

        return "Second Semester";

    }


    return "Academic Calendar";

}


/* =========================================
   GET EVENTS
========================================= */

function getEvents(date) {

    return events.filter(
        event =>
            event.date === date
    );

}


/* =========================================
   RENDER CALENDAR
========================================= */

function renderCalendar() {

    calendarGrid.innerHTML = "";


    const year =
        currentDate.getFullYear();

    const month =
        currentDate.getMonth();


    monthTitle.textContent =
        `${months[month]} ${year}`;


    semesterLabel.textContent =
        getSemester(currentDate);


    const firstDay =
        new Date(year, month, 1);


    const lastDay =
        new Date(year, month + 1, 0);


    const startDay =
        firstDay.getDay();


    const days =
        lastDay.getDate();


    const totalCells =
        Math.ceil(
            (startDay + days) / 7
        ) * 7;


    const previousLastDay =
        new Date(
            year,
            month,
            0
        ).getDate();


    for (
        let i = 0;
        i < totalCells;
        i++
    ) {

        let dayNumber;

        let date;

        let otherMonth = false;


        if (i < startDay) {

            dayNumber =
                previousLastDay -
                startDay +
                i +
                1;

            date =
                new Date(
                    year,
                    month - 1,
                    dayNumber
                );

            otherMonth = true;

        }

        else if (
            i >= startDay + days
        ) {

            dayNumber =
                i -
                (startDay + days) +
                1;

            date =
                new Date(
                    year,
                    month + 1,
                    dayNumber
                );

            otherMonth = true;

        }

        else {

            dayNumber =
                i -
                startDay +
                1;

            date =
                new Date(
                    year,
                    month,
                    dayNumber
                );

        }


        const key =
            dateKey(date);


        const dayEvents =
            getEvents(key);


        const day =
            document.createElement("div");


        day.className = "day";


        if (otherMonth) {

            day.classList.add(
                "other-month"
            );

        }


        const today =
            new Date();


        if (
            key === dateKey(today)
        ) {

            day.classList.add(
                "today"
            );

        }


        const number =
            document.createElement("div");


        number.className =
            "day-number";


        number.textContent =
            dayNumber;


        day.appendChild(number);


        let visibleEvents;


        if (
            activeFilter === "all"
        ) {

            visibleEvents =
                dayEvents;

        }

        else {

            visibleEvents =
                dayEvents.filter(
                    event =>
                        event.type ===
                        activeFilter
                );

        }


        visibleEvents
            .slice(0, 3)
            .forEach(event => {

                const button =
                    document.createElement("button");


                button.className =
                    `event ${event.type}`;


                button.textContent =
                    event.title;


                button.addEventListener(
                    "click",
                    () => openEvent(event)
                );


                day.appendChild(button);

            });


        if (
            visibleEvents.length > 3
        ) {

            const more =
                document.createElement("div");


            more.className =
                "more-events";


            more.textContent =
                `+ ${visibleEvents.length - 3
                } more`;


            day.appendChild(more);

        }


        calendarGrid.appendChild(day);

    }

}


/* =========================================
   OPEN EVENT
========================================= */

function openEvent(event) {

    modalTitle.textContent =
        event.title;


    modalDate.textContent =
        formatDate(event.date);


    modalCategory.textContent =
        categoryNames[event.type];


    modalDescription.textContent =
        event.description;


    modal.classList.add("open");

}


/* =========================================
   CLOSE EVENT
========================================= */

function closeEvent() {

    modal.classList.remove("open");

}


/* =========================================
   UPCOMING EVENTS
========================================= */

function renderUpcoming() {

    const today =
        new Date();


    today.setHours(
        0,
        0,
        0,
        0
    );


    const upcoming =
        events

            .filter(event => {

                return new Date(
                    event.date + "T12:00:00"
                ) >= today;

            })

            .sort(
                (a, b) =>
                    a.date.localeCompare(
                        b.date
                    )
            )

            .slice(0, 6);


    upcomingEvents.innerHTML = "";


    upcoming.forEach(event => {

        const date =
            new Date(
                event.date + "T12:00:00"
            );


        const item =
            document.createElement("button");


        item.className =
            "upcoming-item";


        item.innerHTML = `

            <div class="upcoming-date">

                <strong>
                    ${date.getDate()}
                </strong>

                <span>
                    ${months[
                date.getMonth()
            ].slice(0, 3)}
                </span>

            </div>


            <div class="upcoming-content">

                <strong>
                    ${event.title}
                </strong>

                <span>
                    ${categoryNames[event.type]}
                </span>

            </div>

        `;


        item.addEventListener(
            "click",
            () => openEvent(event)
        );


        upcomingEvents.appendChild(item);

    });

}


