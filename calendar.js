const searchPanel =
    document.getElementById(
        "searchPanel"
    );


const searchInput =
    document.getElementById(
        "eventSearch"
    );


const searchResults =
    document.getElementById(
        "searchResults"
    );


document
    .getElementById("searchToggle")
    .addEventListener(
        "click",
        () => {

            searchPanel.classList.toggle(
                "open"
            );


            if (
                searchPanel.classList.contains(
                    "open"
                )
            ) {

                searchInput.focus();

            }

        }
    );


searchInput.addEventListener(
    "input",
    () => {

        const query =
            searchInput.value
                .toLowerCase()
                .trim();


        searchResults.innerHTML = "";


        if (!query) {

            return;

        }


        const results =
            events.filter(event => {

                return (

                    event.title
                        .toLowerCase()
                        .includes(query)

                    ||

                    event.description
                        .toLowerCase()
                        .includes(query)

                    ||

                    categoryNames[
                        event.type
                    ]
                        .toLowerCase()
                        .includes(query)

                );

            });


        results
            .slice(0, 10)
            .forEach(event => {

                const button =
                    document.createElement(
                        "button"
                    );


                button.className =
                    "search-result";


                button.innerHTML = `

                    <strong>
                        ${event.title}
                    </strong>

                    <span>
                        ${formatDate(event.date)}
                        ·
                        ${categoryNames[event.type]}
                    </span>

                `;


                button.addEventListener(
                    "click",
                    () => {

                        currentDate =
                            new Date(
                                event.date +
                                "T12:00:00"
                            );


                        renderCalendar();

                        openEvent(event);

                    }
                );


                searchResults.appendChild(
                    button
                );

            });

    });


document
    .getElementById("clearSearch")
    .addEventListener(
        "click",
        () => {

            searchInput.value = "";

            searchResults.innerHTML = "";

            searchInput.focus();

        }
    );


